const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const ord = n => {
 const v = n % 100;
 if (v >= 11 && v <= 13) return `${n}th`;
 return n + ({ 1: 'st', 2: 'nd', 3: 'rd' }[n % 10] || 'th');
};

// 日期的几种写法：15 March、March 15、15th March、March 15th，还有日在前的 15/03（攻略 ielts-listening-gaps 也这么说）。
function dateForms(day, month) {
 const name = MONTHS[month - 1];
 const out = [`${day} ${name}`, `${name} ${day}`, `${ord(day)} ${name}`, `${name} ${ord(day)}`];
 const ds = day < 10 ? [`0${day}`, `${day}`] : [`${day}`];
 const ms = month < 10 ? [`0${month}`, `${month}`] : [`${month}`];
 for (const d of ds) for (const m of ms) out.push(`${d}/${m}`);
 return out;
}

// 时间的几种写法：9.30、9:30、09:30，后面可以带 am / pm / a.m.；下午、晚上的时间也可以写 24 小时制。
function timeForms(h, m, half) {
 const mm = String(m).padStart(2, '0');
 const out = [`${h}.${mm}`, `${h}:${mm}`, `${h}.${mm} ${half}`, `${h}:${mm} ${half}`];
 if (half === 'pm') out.push(`${h + 12}:${mm}`, `${h + 12}.${mm}`);
 for (const x of h < 10 ? [`${h}`, `0${h}`] : [`${h}`]) {
  for (const b of [`${x}.${mm}`, `${x}:${mm}`]) out.push(b, `${b} ${half}`, `${b}${half}`, `${b} ${half[0]}.${half[1]}.`);
 }
 return [...new Set(out)];
}

