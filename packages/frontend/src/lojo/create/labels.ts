// The brief the creator pastes into their own agent: what to make, by which format, the words, the rules, how to hand it back.
export function agentBrief(d: {
	plan: { platform: string; medium: string; name: string; form: string; hook: string; beats: string[] };
	formHow: string; cover: string; script: string; chosenTitle: string; titles: string[]; body: string; pin: string; ai: string; noteUrl: string;
}): string {
	const video = /视频/.test(d.plan.medium);
	const title = d.chosenTitle || d.titles[0] || '';
	return [
		`帮我把下面这份文案做成${d.plan.platform || '小红书'}的${video ? '竖屏视频（9:16）' : '图文（3:4，1080×1440）'}。做好以后先给我看，不要自己发到平台上。`,
		`## 做法：${d.plan.name}\n${d.plan.hook ? `开头：${d.plan.hook}\n` : ''}${d.plan.beats.map((b, i) => `${i + 1}. ${b}`).join('\n')}${d.formHow ? `\n\n这个做法 Vibes 拆过爆款（形式卡「${d.plan.form}」），照着做：\n${d.formHow}` : ''}`,
		`## 封面大字\n${d.cover}`,
		`## ${video ? '口播稿' : '每一页的大字'}\n${d.script}`,
		`## 发布文案（原样用）\n标题：${title}\n\n正文：\n${d.body}${d.pin ? `\n\n置顶评论：${d.pin}` : ''}${d.ai ? `\n\nAI 声明：${d.ai}` : ''}`,
		'## 要求\n- 图里、视频里的字照上面写，事实不要改。拿不准的先问我。\n- 文案里有「[这里放你的经历]」这类占位的，先问我，不要编。\n- 素材只用你自己做的、我给的、或开放授权的，写明出处。不用别人的截图、照片和视频，不放真人的脸。',
		`原始内容（Vibes 社区）：${d.noteUrl}`,
	].join('\n\n');
}
